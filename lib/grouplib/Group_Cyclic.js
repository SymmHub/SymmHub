import {
    sin,
    cos,
    sqrt,
    TORADIANS,
    Group,
    EventProcessor,
    ParamFloat,
    ParamBool,
    setParamValues,
    iPlane,
    iSphere,
    iReflectU4,
}
from './modules.js';

const DEBUG = false;
const MYNAME = 'Group_Cyclic';

/*
  cyclic group generated by one loxodromic Möbius transformation

      z -> AbsLambda^2 exp(2 i ArgLambda) z

  the composition of the inversions in the unit circle and in the circle of radius
  AbsLambda (a dilation) with the reflections in the x axis and in the line through the
  origin at the angle ArgLambda (a rotation). The fundamental domain is the annulus
  between the circles of radii AbsLambda and 1/AbsLambda, paired by the generator; the
  quotient is a torus. The fixed points are 0 and infinity; finiteFP reflects everything
  in Sphere([1, 0, 0, sqrt 2]), which brings both fixed points to finite points.

  Not an orbifold group of any geometry (the wallpaper torus 'o' is Euclidean and the
  orbifold builder geometrizes), so nothing else in SymmHub makes it.

  Imported from the Orb repo (examples/jslibm/Group_Cyclic.js, 2026-10-26) with its
  parameter names (AbsLambda, ArgLambda in degrees, finiteFP), so the group blocks of the
  old presets load unchanged.
*/
export class Group_Cyclic {

    constructor() {

        this.params = {
            AbsLambda: 1.1,
            ArgLambda: 0,
            finiteFP: false,
        };

        this.mParams = this.makeParams();
        this.state = {
            paramChanged: true,
            group: null,
        };
    }

    getClassName(){
        return MYNAME;
    }

    setOptions(opt){
        if(opt.onChanged){
            this.onGroupChanged = opt.onChanged;
            this.eventProcessor = new EventProcessor();
            this.eventProcessor.addEventListener('onChanged', this.onGroupChanged);
        }
    }

    //
    //  return external params
    //
    getParams(){
        return this.mParams;
    }

    makeParams() {

        const par = this.params;
        const opc = this.onParamChanged.bind(this);

        return {
            AbsLambda: ParamFloat({obj: par, key: 'AbsLambda', min: 0.1, max: 10, step: 0.0001, onChange: opc}),
            ArgLambda: ParamFloat({obj: par, key: 'ArgLambda', min: -360, max: 360, step: 0.01, onChange: opc}),
            finiteFP:  ParamBool({obj: par, key: 'finiteFP', onChange: opc}),
        };
    }

    //
    // called from UI when any group param was changed
    //
    onParamChanged() {

        this.state.paramChanged = true;
        if(DEBUG) console.log(`${MYNAME}.onParamChanged()`);
        if(this.eventProcessor){
            this.eventProcessor.handleEvent({type: 'onChanged', target: this});
        }
    }

    //
    // set parameters from saved paramMap
    //
    setParamsMap(paramsMap) {
        setParamValues(this.mParams, paramsMap);
    }

    //
    //  return group description
    //
    getGroup() {

        if(this.state.paramChanged) {
            this.state.group = this.calculateGroup();
            this.state.paramChanged = false;
        }
        return this.state.group;
    }

    calculateGroup(){

        const p = this.params;
        const r1 = p.AbsLambda;
        const a = p.ArgLambda*TORADIANS;

        let s0  = iSphere([0, 0, 0, -1]);      // unit circle
        let s1  = iSphere([0, 0, 0, r1]);      // outer side of the annulus
        let s1a = iSphere([0, 0, 0, -1./r1]);  // inner side of the annulus
        let p0  = iPlane([0, -1, 0, 0]);       // the x axis
        let p1  = iPlane([-sin(a), cos(a), 0, 0]); // the line at the angle a

        if(p.finiteFP){
            const ref = iSphere([1, 0, 0, sqrt(2)]);
            [s0, s1, s1a, p0, p1] = [s0, s1, s1a, p0, p1].map(s => iReflectU4(ref, s));
        }

        // [s1, s0, p1, p0] maps the cell across s1 back into the annulus (s1 onto s1a)
        const group = new Group({s: [s1, s1a], t: [[s1, s0, p1, p0], [p0, p1, s0, s1]]});
        if(DEBUG) console.log(`${MYNAME} returning: `, group);
        return group;
    }

} // class Group_Cyclic
