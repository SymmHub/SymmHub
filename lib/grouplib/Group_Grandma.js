import {
    Group,
    EventProcessor,
    ParamFloat,
    ParamInt,
    ParamBool,
    ParamChoice,
    setParamValues,
    iPoint,
    cMul,
    cDiv,
    cAdd,
    cSub,
    csqrt,
    carrierGroup,
    dirichletDomain,
}
from './modules.js';

const DEBUG = false;
const MYNAME = 'Group_Grandma';

const DOMAIN_DIRICHLET = 'dirichlet';
const DOMAIN_ISOMETRIC = 'isometric circles';
const DOMAINS = [DOMAIN_DIRICHLET, DOMAIN_ISOMETRIC];

/*
  Grandma's recipe (Mumford, Series, Wright: Indra's Pearls, chapter 8, Box 21): the
  group generated by two Möbius transformations a and b with the traces

      tr a = ta,   tr b = tb,   tr ab = tab,

  tab the root of the Markov identity  tab^2 - ta tb tab + ta^2 + tb^2 = 0  taken with
  the minus sign of the square root (the other root with `otherRoot`), which makes the
  commutator abAB parabolic with trace -2. The recipe normalizes the pair:

      z0 = (tab - 2) tb / (tb tab - 2 ta + 2 i tab)
      a  = ( ta/2,  (ta tab - 2 tb + 4i) / ((2 tab + 4) z0) ;
             (ta tab - 2 tb - 4i) z0 / (2 tab - 4),  ta/2 )
      b  = ( (tb - 2i)/2,  tb/2 ;  tb/2,  (tb + 2i)/2 )

  Real traces with tab real too (ta^2 tb^2 >= 4 ta^2 + 4 tb^2) give a Fuchsian group of
  the unit disk, the limit set is the unit circle (ta = tb = 3: the group of a
  once-punctured torus, the puncture is the parabolic commutator); complex traces
  near them give the quasi-Fuchsian groups of the book (ta = 1.91 + 0.05 i, tb = 3:
  the spirals of chapter 8; ta = 1.87 + 0.1 i, tb = 1.87 - 0.1 i: the double spirals),
  a trace 2 a cusp group (ta = 2, tb = 3). Traces far from these give groups that are
  not discrete: the domain below is then no fundamental domain and the tiling
  overlaps.

  The generators act on the plane z = 0 as Möbius transformations; mobiusToSplanes
  (lib/invlib/MobiusMatrix.js) writes each as a chain of at most four reflections
  (carrierGroup in MobiusGenerators.js).

  The fundamental domain:
    dirichlet          the Dirichlet domain of the base point (baseX, baseY)
                       (dirichletDomain in MobiusGenerators.js: the bisectors of the
                       base and its images under the words of at most `depth` letters
                       in a, A, b, B that bound the cell of the base, closed under
                       inverses, products and the generator folds); images with a
                       scale factor below minScale (near the limit set) are left out.
                       A base point near the limit set gets a thin domain of long
                       words; the search stops after a time budget. For ta = tb = 3
                       and the base at the origin it is the eight-sided domain of the
                       punctured torus with its corners at the puncture's orbit.
    isometric circles  the exterior of the isometric circles of a, A, b, B, paired by
                       the generators (a Ford domain when the circles do not overlap,
                       as for Schottky-like traces; for ta = tb = 3 they overlap).
  The side names of the Dirichlet group are its own (a, b, c, ...); its words in
  a, A, b, B are kept as dirichletWords, as the Dirichlet domain operation does.
*/
export class Group_Grandma {

    constructor() {

        this.params = {
            ta_re: 3,
            ta_im: 0,
            tb_re: 3,
            tb_im: 0,
            otherRoot: false,
            domain: DOMAIN_DIRICHLET,
            baseX: 0,
            baseY: 0,
            depth: 4,
            minScale: 0.001,
        };

        this.mParams = this.makeParams();
        this.state = {
            paramChanged: true,
            group: null,
        };
    }

    getClassName(){
        return MYNAME;
    }

    setOptions(opt){
        if(opt.onChanged){
            this.onGroupChanged = opt.onChanged;
            this.eventProcessor = new EventProcessor();
            this.eventProcessor.addEventListener('onChanged', this.onGroupChanged);
        }
    }

    //
    //  return external params
    //
    getParams(){
        return this.mParams;
    }

    makeParams() {

        const par = this.params;
        const opc = this.onParamChanged.bind(this);
        const trace = (key, name) => ParamFloat({obj: par, key: key, name: name, min: -4, max: 4, step: 1e-10, onChange: opc});
        const coord = key => ParamFloat({obj: par, key: key, min: -2, max: 2, step: 1e-10, onChange: opc});

        return {
            ta_re:     trace('ta_re', 'Re ta'),
            ta_im:     trace('ta_im', 'Im ta'),
            tb_re:     trace('tb_re', 'Re tb'),
            tb_im:     trace('tb_im', 'Im tb'),
            otherRoot: ParamBool({obj: par, key: 'otherRoot', name: 'other root', onChange: opc}),
            domain:    ParamChoice({obj: par, key: 'domain', choice: DOMAINS, onChange: opc}),
            baseX:     coord('baseX'),
            baseY:     coord('baseY'),
            depth:     ParamInt({obj: par, key: 'depth', min: 1, max: 8, onChange: opc}),
            minScale:  ParamFloat({obj: par, key: 'minScale', name: 'min scale', min: 0, max: 1, step: 1e-10, onChange: opc}),
        };
    }

    //
    // called from UI when any group param was changed
    //
    onParamChanged() {

        this.state.paramChanged = true;
        if(DEBUG) console.log(`${MYNAME}.onParamChanged()`);
        if(this.eventProcessor){
            this.eventProcessor.handleEvent({type: 'onChanged', target: this});
        }
    }

    //
    // set parameters from saved paramMap
    //
    setParamsMap(paramsMap) {
        setParamValues(this.mParams, paramsMap);
    }

    //
    //  return group description
    //
    getGroup() {

        if(this.state.paramChanged) {
            const group = this.calculateGroup();
            if(group) this.state.group = group;
            this.state.paramChanged = false;
        }
        return this.state.group;
    }

    //
    //  the generators of the recipe: {a, b, tab} with a, b as 2x2 complex matrices
    //
    getGenerators(){
        const p = this.params;
        return grandmaRecipe([p.ta_re, p.ta_im], [p.tb_re, p.tb_im], p.otherRoot);
    }

    calculateGroup(){

        const p = this.params;
        const {a, b} = this.getGenerators();
        const g0 = carrierGroup([{name: 'a', m: a}, {name: 'b', m: b}]);
        if(!g0){
            console.warn(`${MYNAME}: the generators of ta = ${p.ta_re} + ${p.ta_im} i, tb = ${p.tb_re} + ${p.tb_im} i are degenerate, the group is kept as it was`);
            return null;
        }
        if(p.domain === DOMAIN_ISOMETRIC) return g0;

        const base = iPoint([p.baseX, p.baseY, 0, 0]);
        const dg = dirichletDomain(g0, base, p.depth, p.minScale);
        if(!dg){
            console.warn(`${MYNAME}: no Dirichlet domain at the base (${p.baseX}, ${p.baseY}) with words of ${p.depth} letters, the isometric circles are used`);
            return g0;
        }
        if(DEBUG) console.log(`${MYNAME}: ${dg.getFundDomain().length} sides`, dg.dirichletWords);
        return dg;
    }

} // class Group_Grandma


/**
  Grandma's recipe (Box 21): the generators a, b of traces ta, tb (complex numbers
  [re, im]) with tr abAB = -2, and the trace tab of ab

  return {a, b, tab}
*/
export function grandmaRecipe(ta, tb, otherRoot = false){

    const two = [2, 0], four = [4, 0], i2 = [0, 2], i4 = [0, 4];
    const tatb = cMul(ta, tb);
    // tab^2 - ta tb tab + ta^2 + tb^2 = 0
    const disc = cSub(cMul(tatb, tatb), cMul(four, cAdd(cMul(ta, ta), cMul(tb, tb))));
    const root = csqrt(disc);
    const tab = cDiv(otherRoot ? cAdd(tatb, root) : cSub(tatb, root), two);

    const z0 = cDiv(cMul(cSub(tab, two), tb),
                    cAdd(cSub(cMul(tb, tab), cMul(two, ta)), cMul(i2, tab)));
    const ta2 = cDiv(ta, two);
    const tatab2tb = cSub(cMul(ta, tab), cMul(two, tb));   // ta tab - 2 tb
    const a = [[ta2, cDiv(cAdd(tatab2tb, i4), cMul(cAdd(cMul(two, tab), four), z0))],
               [cDiv(cMul(cSub(tatab2tb, i4), z0), cSub(cMul(two, tab), four)), ta2]];
    const tb2 = cDiv(tb, two);
    const b = [[cDiv(cSub(tb, i2), two), tb2],
               [tb2, cDiv(cAdd(tb, i2), two)]];
    return {a, b, tab};
}
