import { ITransform, iPoint, SPLANE_PLANE, U4 } from '../invlib/invlib.js';
import {
    iReflectU4,
    iSphere,
    sameTransform,
} from './modules.js';

const MYNAME = 'GroupPresentation';
const EPS = 1e-7;
const MAX_CYCLE_LENGTH = 100;
const MAX_FOLD_ITERATIONS = 200;
const LETTERS = 'abcdefghijklmnopqrstuvwxyz';
const TWO_PI = 2*Math.PI;
const IDEAL_ANGLE = 1e-5;       // tangent sides, below this angle between them
const MAX_MIRROR_ORDER = 1000;  // of the product of two reflections

/*
  GroupPresentation.js

  Derives a presentation (generators and relators) of a plane group from its
  fundamental domain and pairing transforms, after Poincare's polygon theorem.
  A group given another fundamental domain has other pairing transforms, hence
  other generators and relators; this is what makes such a group usable with
  the subgroup enumeration of sublib, which works from a presentation.

  generators
    one per side of the domain, named a, b, c, ... for sides 0, 1, 2, ...
    Generator i is the direct transform of side i, which maps the domain onto
    the cell across side i.

  the chart
    the sides are lines and circles and the domain may be unbounded, or have
    holes.  Inverting the plane about a point outside the domain makes every
    side a circle and the domain bounded, and the rest works on circles alone:
    a side is one arc of its circle or more, a whole circle when no other side
    meets it.  Sides on one circle share its arcs; the first has them, the rest
    are spare and get a relator of their own below.

  sub sides
    a cell across a side need not cover the whole side: in 2222 the 2-fold
    points may sit off the side midpoints, and a side then touches two cells.
    Every arc is therefore split into the segments touched by the cells across
    it; folding a point just outside a segment into the domain gives the
    transform of that cell as a word in the generators.  For a plain polygon
    each side is one segment and the word is one letter.

  side pairing relators
    the transform of a segment maps it onto another segment of the boundary,
    and the transform of that one is its inverse: w_i * w_j = 1.  A segment
    paired with itself (a 2-fold rotation about its midpoint, or a reflection
    in the side) gives w_i^2 = 1.

  corner cycle relators
    leaving a vertex of the refined domain through one of its segments, the
    transform brings us to another vertex (the same vertex of the cell across
    the segment, seen from the domain); leaving that vertex through its other
    segment continues the walk, which closes when the start vertex is reached
    through its other segment.  The angles met on the way add up to 2*PI/m and
    the product of the transforms is a rotation by that angle, so its m-th
    power is the identity.  Every vertex belongs to exactly one such cycle, but
    for tangent sides: they meet at a point of the limit set and give no relator.

  reflection groups
    a group generated by the reflections in the sides of its domain takes
    Coxeter's presentation from the angles between the mirrors, with no walk:
    those mirrors may meet above the plane or not reach it at all.

  Words act left to right, as in sublib: the word 'ab' means "apply a, then
  b"; an upper case letter is the inverse of the generator.  Each relator is
  verified numerically before it is returned, and an error is thrown when the
  transforms do not tile the plane with the domain.  Domains twisted so far that
  the cells overlap (they do tile hyperbolic space, not its boundary) fail here;
  such a maker derives from an untwisted copy of itself: derivedPresentation.

  Usage:
    const pres = groupPresentation(group);
    subgroupsData({ name: '632', gens: pres.gens, relators: pres.relators, maxIndex: 6 });
*/

function xyOf(p){ return [p.v[0], p.v[1]]; }
function pnt(xy){ return iPoint([xy[0], xy[1], 0, 0]); }
function dist(p, q){ return Math.hypot(p[0]-q[0], p[1]-q[1]); }
function sigDist(side, xy){ return U4.sigDistanceSP(side, pnt(xy)); }
function apply(itrans, xy){ return xyOf(itrans.transform(pnt(xy))); }

/** intersection point of two lines given as planes, null when parallel */
function lineIntersection(p, q){
  const [a1, b1, , d1] = p.v, [a2, b2, , d2] = q.v;
  const det = a1*b2 - a2*b1;
  if(Math.abs(det) < 1e-12) return null;
  return [(d1*b2 - d2*b1)/det, (a1*d2 - a2*d1)/det];
}

/** inverse of a word in the left to right convention: reversed letters, case swapped */
function inverseWord(word){
  let out = '';
  for(let i = word.length - 1; i >= 0; i--){
    const ch = word[i];
    out += (ch === ch.toLowerCase()) ? ch.toUpperCase() : ch.toLowerCase();
  }
  return out;
}

/** free reduction of a word: cancels adjacent inverse letters */
function freeReduce(word){
  const out = [];
  for(const ch of word){
    const last = out[out.length - 1];
    if(last && last !== ch && last.toLowerCase() === ch.toLowerCase()) out.pop();
    else out.push(ch);
  }
  return out.join('');
}

/** a relator up to where it starts and its direction: the least of those words */
function relatorClass(word){
  let best = word;
  for(const w of [word, inverseWord(word)]){
    for(let k = 0; k < w.length; k++){
      const r = w.slice(k) + w.slice(0, k);
      if(r < best) best = r;
    }
  }
  return best;
}

/** sublib spelling of a word: letters separated by '*' */
const wordString = (word) => word.split('').join('*');

/** sublib spelling of word^m */
function powerString(word, m){
  if(m === 1) return wordString(word);
  return (word.length === 1) ? `${word}^${m}` : `(${wordString(word)})^${m}`;
}

/**
  corners of a fundamental domain given as the intersection of half planes
  (a bounded convex polygon with straight sides)

  return array of {point:[x,y], sides:[i,j], angle}, angle is the interior angle
*/
export function domainCorners(sides){

  sides.forEach((s, i) => {
    if(s.type !== SPLANE_PLANE)
      throw new Error(`${MYNAME}: side ${i} is not a straight line, only polygonal domains are supported`);
  });
  const n = sides.length;
  const corners = [];
  for(let i = 0; i < n; i++){
    for(let j = i + 1; j < n; j++){
      const p = lineIntersection(sides[i], sides[j]);
      if(!p) continue;
      // a corner of the polygon lies on the inner side of every other side
      let inside = true;
      for(let k = 0; k < n && inside; k++){
        if(k !== i && k !== j && sigDist(sides[k], p) > EPS) inside = false;
      }
      if(!inside) continue;
      // interior angle: PI minus the angle between the outward normals
      const [ax, ay] = sides[i].v, [bx, by] = sides[j].v;
      const c = Math.max(-1, Math.min(1, ax*bx + ay*by));
      corners.push({ point: p, sides: [i, j], angle: Math.PI - Math.acos(c) });
    }
  }
  return corners;
}

/** a point of the plane outside the domain and off every side */
function inversionCenter(sides){
  const candidates = [];
  const turns = [0.3, 1.1, 1.9, 2.7, 3.5, 4.3, 5.1, 5.9];
  for(const s of sides){
    if(s.type === SPLANE_PLANE){
      const [nx, ny, , d] = s.v;
      for(const out of [0.25, 0.5, 1, 2]){
        for(const along of [-2, -1, -0.5, 0, 0.5, 1, 2]){
          candidates.push([nx*(d + out) - ny*along, ny*(d + out) + nx*along]);
        }
      }
    } else {
      const [cx, cy, , r] = s.v;
      const R = Math.abs(r);
      for(const f of (r < 0) ? [0, 0.25, 0.5, 0.75] : [1.25, 1.5, 2, 3]){
        for(const a of turns) candidates.push([cx + f*R*Math.cos(a), cy + f*R*Math.sin(a)]);
      }
    }
  }
  let best = null, margin = 0;
  for(const c of candidates){
    const d = sides.map(s => sigDist(s, c));
    if(Math.max(...d) <= 0) continue;                  // inside the domain
    const m = Math.min(...d.map(Math.abs));
    if(m > margin){ margin = m; best = c; }
  }
  return best;
}

/**
  the sides and transforms of a group seen through an inversion centred outside the
  domain: every side is a circle and the domain is bounded, whatever it was before

  return {sides, rev, direct}: the sides as circles of the chart, the transforms as
  arrays of splanes of the chart
*/
function circularChart(group){

  const sides = group.getFundDomain();
  const center = inversionCenter(sides);
  if(!center) throw new Error(`${MYNAME}: no point outside the domain`);

  const inversion = (R) => iSphere([center[0], center[1], 0, R]);
  const extent = group.getFundDomain().reduce((e, s) => {
    const c = iReflectU4(inversion(1), s);
    return Math.max(e, Math.hypot(c.v[0] - center[0], c.v[1] - center[1]) + Math.abs(c.v[3]));
  }, 0);
  const ref = inversion(1/Math.sqrt(extent));           // the circles fill the unit disk
  const framed = (t) => t.map(s => iReflectU4(ref, s));

  const circles = framed(sides);
  circles.forEach((s, i) => {
    if(s.type === SPLANE_PLANE || Math.abs(s.v[2]) > EPS)
      throw new Error(`${MYNAME}: side ${i} does not lie in the plane`);
  });
  return { sides: circles, rev: group.getReverseTransforms().map(framed), direct: group.getTransforms().map(framed) };
}

/** the points two circles {x, y, r} meet at, one when they touch */
function circleCrossings(a, b, tol){
  const dx = b.x - a.x, dy = b.y - a.y;
  const d = Math.hypot(dx, dy);
  if(d < tol || d > a.r + b.r + tol || d < Math.abs(a.r - b.r) - tol) return [];
  const along = (d*d + a.r*a.r - b.r*b.r)/(2*d);
  const ux = dx/d, uy = dy/d;
  const P = [a.x + ux*along, a.y + uy*along];
  if(Math.abs(d - a.r - b.r) < tol || Math.abs(d - Math.abs(a.r - b.r)) < tol) return [P];
  const h = Math.sqrt(Math.max(0, a.r*a.r - along*along));
  return [[P[0] - uy*h, P[1] + ux*h], [P[0] + uy*h, P[1] - ux*h]];
}

/** the circles of the chart as {x, y, r, sign}, sign < 0 for a domain outside the circle */
const circlesOf = (sides) => sides.map(s => ({ x: s.v[0], y: s.v[1], r: Math.abs(s.v[3]), sign: Math.sign(s.v[3]) }));

/** the order of the product of the reflections in two circles, 0 when it has none */
function mirrorOrder(a, b){
  const d2 = (a.x - b.x)**2 + (a.y - b.y)**2;
  const c = (d2 - a.r*a.r - b.r*b.r)/(2*a.r*b.r);
  if(Math.abs(c) > 1 - 1e-9) return 0;                 // disjoint or tangent
  const turn = Math.acos(c)/Math.PI;                   // a half turn is 1
  for(let m = 2; m <= MAX_MIRROR_ORDER; m++){
    if(Math.abs(m*turn - Math.round(m*turn)) < 1e-8) return m;
  }
  return 0;
}

/**
  the presentation of a group generated by the reflections in the sides of its domain:
  every generator has order 2 and two mirrors meet in the order of their product.
  This is Coxeter's presentation, Poincare's theorem for a polyhedron of hyperbolic
  space, and it needs no walk around the domain: such a group may have mirrors which
  meet above the plane or do not reach it at all, and those show on no corner.
*/
function reflectionPresentation(circles, names){
  const relatorList = names.map(name => `${name}^2`);
  circles.forEach((a, i) => {
    for(let j = i + 1; j < circles.length; j++){
      const order = mirrorOrder(a, circles[j]);
      if(order) relatorList.push(powerString(names[i] + names[j], order));
    }
  });
  return { gens: names.join(' '), relators: relatorList.join(', '), genNames: names, relatorList,
           subSides: [], pairing: [], vertices: [], cycles: [] };
}

/** is every transform of the group the reflection in its own side? */
function isReflectionGroup(group){
  const sides = group.getFundDomain();
  return group.getReverseTransforms().every((t, i) => t.length === 1 && t[0].type === sides[i].type &&
                                                      t[0].v.every((x, k) => Math.abs(x - sides[i].v[k]) < EPS));
}

/** counter clockwise angle from a to b, in [0, 2 PI) */
function ccw(a, b){
  const t = (b - a) % TWO_PI;
  return (t < 0) ? t + TWO_PI : t;
}

/**
  the arcs of the sides on the boundary of the domain, each from t0 to t1 counter
  clockwise on the circle of its side; a whole circle is one arc with whole = true.
  Sides on one circle share its arcs: the first one has them, and the rest are in
  `spare` (the half turn about a point of a side splits it in two sides on one line).
*/
function boundaryArcs(sides, circles, tol){

  const inside = (P, skip) => sides.every((s, k) => skip.includes(k) || sigDist(s, P) <= tol);
  const sameCircle = (i, j) => Math.hypot(circles[i].x - circles[j].x, circles[i].y - circles[j].y) < tol &&
                               Math.abs(circles[i].r - circles[j].r) < tol && circles[i].sign === circles[j].sign;

  const arcs = [];
  const spare = [];
  for(let i = 0; i < sides.length; i++){
    const twins = sides.map((s, k) => k).filter(k => k === i || sameCircle(i, k));
    if(twins[0] !== i){ spare.push(i); continue; }
    const c = circles[i];
    const cuts = [];
    for(let j = 0; j < sides.length; j++){
      if(twins.includes(j)) continue;
      for(const P of circleCrossings(c, circles[j], tol)){
        if(!inside(P, [...twins, j])) continue;
        const t = Math.atan2(P[1] - c.y, P[0] - c.x);
        if(!cuts.some(u => Math.min(ccw(u, t), ccw(t, u))*c.r < tol)) cuts.push(t);
      }
    }
    cuts.sort((a, b) => a - b);
    const before = arcs.length;
    const add = (t0, t1, whole) => {
      const tm = (t0 + t1)/2;
      if(inside([c.x + c.r*Math.cos(tm), c.y + c.r*Math.sin(tm)], twins)) arcs.push({ side: i, t0, t1, whole });
    };
    if(cuts.length === 0) add(0, TWO_PI, true);
    cuts.forEach((t, k) => {
      const next = (k + 1 < cuts.length) ? cuts[k + 1] : cuts[0] + TWO_PI;
      add(t, next, false);
    });
    if(arcs.length === before) spare.push(i);           // a side which bounds nothing
  }
  return { arcs, spare };
}

/**
  presentation of the group from its fundamental domain and pairing transforms

  group: invlib Group whose fundamental domain is bounded by lines and circles of
         the plane, with one pairing transform per side

  return {
    gens:        'a b c'                      generator names, one per side
    relators:    'a^2, b*c, b^3, (a*b)^6'     relators in the sublib syntax
    genNames:    ['a','b','c']
    relatorList: the relators as an array
    subSides:    array of {side, t0, t1, word, directWord}: the arcs of the sides
                 touched by the cells across them, in the angles of the chart; word
                 is the transform which maps that cell onto the domain, directWord
                 its inverse (the generator for a plain side)
    pairing:     pairing[i] == j when the transform of arc i maps it onto arc j
    vertices:    the ends of the arcs, {point, angle, subSides, ideal}, in the chart
    cycles:      array of {vertices:[...], subSides:[...], order:m, word}: the
                 vertex cycles, the arcs left through on the way, the order of the
                 cycle transform and the relator word (without the power)
  }
*/
export function groupPresentation(group){

  const count = group.getFundDomain().length;
  if(count > LETTERS.length) throw new Error(`${MYNAME}: ${count} sides, sublib names ${LETTERS.length} generators`);
  const names = LETTERS.slice(0, count).split('');

  const chart = circularChart(group);
  const sides = chart.sides;
  const rev = chart.rev.map((t, i) => new ITransform(t, names[i].toUpperCase()));
  const direct = chart.direct.map((t, i) => new ITransform(t, names[i]));
  const circles = circlesOf(sides);
  if(isReflectionGroup(group)) return reflectionPresentation(circles, names);

  const identity = new ITransform([], '');
  const tol = EPS;

  // letters -> transforms, to evaluate words
  const letterTransform = {};
  names.forEach((name, i) => {
    letterTransform[name] = direct[i];
    letterTransform[name.toUpperCase()] = rev[i];
  });
  const evaluate = (word, power) => {
    let t = new ITransform([], '');
    for(let k = 0; k < power; k++){
      for(const ch of word){
        if(!letterTransform[ch]) throw new Error(`${MYNAME}: unknown letter '${ch}' in word ${word}`);
        t = t.concat(letterTransform[ch]);
      }
    }
    return t;
  };

  // folds a point into the domain with the pairing transforms, as the shaders
  // do; the accumulated word names the cell the point came from
  const fold = (xy) => {
    let p = pnt(xy);
    let total = new ITransform([], '');
    for(let k = 0; k < MAX_FOLD_ITERATIONS; k++){
      const i = sides.findIndex(s => U4.sigDistanceSP(s, p) > 0);
      if(i < 0) return total;
      p = rev[i].transform(p);
      total = total.concat(rev[i]);
    }
    return null;
  };

  // ---- the sides as arcs of circles ------------------------------------------------
  const pointOn = (i, t) => [circles[i].x + circles[i].r*Math.cos(t), circles[i].y + circles[i].r*Math.sin(t)];
  const angleOn = (i, P) => Math.atan2(P[1] - circles[i].y, P[0] - circles[i].x);
  const onCircle = (i, P) => Math.abs(Math.hypot(P[0] - circles[i].x, P[1] - circles[i].y) - circles[i].r) < 10*tol;
  // the unit normal out of the domain at the angle t of side i
  const normalAt = (i, t) => [circles[i].sign*Math.cos(t), circles[i].sign*Math.sin(t)];

  const { arcs, spare } = boundaryArcs(sides, circles, tol);
  if(arcs.length === 0) throw new Error(`${MYNAME}: the sides bound nothing`);
  for(const a of arcs){
    a.mid = pointOn(a.side, (a.t0 + a.t1)/2);
    a.A = pointOn(a.side, a.t0);
    a.B = pointOn(a.side, a.t1);
  }

  // points inside the domain, off the side of each arc: no transform but the identity
  // fixes them, and the transforms are well conditioned there
  const insideOf = (arc) => {
    const n = normalAt(arc.side, (arc.t0 + arc.t1)/2);
    for(let d = 0.01; d > 1e-6; d /= 2){
      const P = [arc.mid[0] - n[0]*d, arc.mid[1] - n[1]*d];
      if(sides.every(s => sigDist(s, P) < -tol)) return P;
    }
    return null;
  };
  const inner = arcs.map(insideOf).filter(P => P);
  if(inner.length === 0) throw new Error(`${MYNAME}: no point inside the domain`);
  const testPoints = [inner[0], inner[inner.length >> 1], inner[inner.length - 1]].map(pnt);

  // what of the arc lies on the arc b once G maps b onto the circle of side i: the
  // stretch [lo, hi] of angles around tm, null when G(b) is elsewhere
  const stretchOf = (b, G, i, tm) => {
    const M = apply(G, b.mid), E1 = apply(G, b.A), E2 = apply(G, b.B);
    if(!onCircle(i, M) || !onCircle(i, E1) || !onCircle(i, E2)) return null;
    if(b.whole || b.t1 - b.t0 > TWO_PI - 1e-9) return [-Infinity, Infinity];
    const e1 = angleOn(i, E1), e2 = angleOn(i, E2), m = angleOn(i, M);
    const [start, end] = (ccw(e1, m) < ccw(e1, e2)) ? [e1, e2] : [e2, e1];
    const span = ccw(start, end);
    const back = ccw(start, tm);
    if(back > span + 10*tol/circles[i].r && TWO_PI - back > 10*tol/circles[i].r) return null;
    const lo = (back > span) ? tm : tm - back;
    return [lo, lo + span];
  };

  // ---- refinement: the arcs of each side touched by the cells across it ------------
  const subSides = [];
  arcs.forEach((arc) => {
    const i = arc.side;
    const r = circles[i].r;
    const atol = tol/r;
    const pieces = [];
    const queue = [[arc.t0, arc.t1]];
    let guard = 0;
    while(queue.length){
      if(++guard > 1000) throw new Error(`${MYNAME}: side ${i} cannot be covered by the cells across it`);
      const [t0, t1] = queue.pop();
      if(t1 - t0 < atol) continue;
      const tm = (t0 + t1)/2;
      const mid = pointOn(i, tm), n = normalAt(i, tm);
      const T = fold([mid[0] + n[0]*10*tol, mid[1] + n[1]*10*tol]);    // the cell across -> domain
      if(!T) throw new Error(`${MYNAME}: a point across side ${i} does not fold into the domain`);
      const G = T.getInverse();                                        // domain -> the cell across
      let stretch = null;
      for(let k = 0; k < arcs.length && !stretch; k++) stretch = stretchOf(arcs[k], G, i, tm);
      if(!stretch) throw new Error(`${MYNAME}: the cell across side ${i} has no side on the circle of side ${i}`);
      const lo = Math.max(t0, stretch[0]), hi = Math.min(t1, stretch[1]);
      if(hi - lo < atol) throw new Error(`${MYNAME}: the cell found across side ${i} does not touch it`);
      pieces.push({ side: i, arc, t0: lo, t1: hi, trans: T, word: T.word });
      if(lo - t0 > atol) queue.push([t0, lo]);
      if(t1 - hi > atol) queue.push([hi, t1]);
    }
    pieces.sort((p, q) => p.t0 - q.t0);
    let t = arc.t0;
    for(const p of pieces){
      if(Math.abs(p.t0 - t) > 10*atol) throw new Error(`${MYNAME}: side ${i} is not covered by the cells across it`);
      t = p.t1;
    }
    if(Math.abs(t - arc.t1) > 10*atol) throw new Error(`${MYNAME}: side ${i} is not covered by the cells across it`);
    for(const p of pieces){
      p.P0 = pointOn(i, p.t0);
      p.P1 = pointOn(i, p.t1);
      p.mid = pointOn(i, (p.t0 + p.t1)/2);
      p.directWord = inverseWord(p.word);
      subSides.push(p);
    }
  });

  // ---- vertices of the refined domain ----------------------------------------------
  const vertices = [];
  const vertexAt = (P) => vertices.findIndex(v => dist(v.point, P) < 10*tol);
  subSides.forEach((s, si) => {
    if(s.arc.whole) return;
    [[s.P0, s.t0], [s.P1, s.t1]].forEach(([P, t]) => {
      let vi = vertexAt(P);
      if(vi < 0){
        vertices.push({ point: P, angle: Math.PI, subSides: [], normals: [], ideal: false });
        vi = vertices.length - 1;
      }
      vertices[vi].subSides.push(si);
      vertices[vi].normals.push(normalAt(s.side, t));
    });
  });
  // the sides at a vertex, by their normals out of the domain; tangent sides meet at a
  // point of the limit set, where no relator comes from (a cusp, however many corners
  // of the domain go there)
  vertices.forEach((v, vi) => {
    const dots = v.normals.map(n => n[0]*v.normals[0][0] + n[1]*v.normals[0][1]);
    if(v.subSides.length === 2){
      v.angle = Math.PI - Math.acos(Math.max(-1, Math.min(1, dots[1])));
      v.ideal = v.angle < IDEAL_ANGLE;
    } else {
      v.ideal = dots.every(c => Math.abs(c) > 1 - 1e-9);
      if(!v.ideal) throw new Error(`${MYNAME}: vertex ${vi} at (${v.point}) has ${v.subSides.length} segments`);
    }
  });

  // ---- pairing of the arcs ---------------------------------------------------------
  const pairing = subSides.map((s, si) => {
    const Q = apply(s.trans, s.mid);
    const j = subSides.findIndex(r => {
      if(!onCircle(r.side, Q)) return false;
      const t = r.t0 + ccw(r.t0, angleOn(r.side, Q));
      return t <= r.t1 + 10*tol/circles[r.side].r;
    });
    if(j < 0) throw new Error(`${MYNAME}: the transform of segment ${si} of side ${s.side} does not map it onto the boundary of the domain`);
    return j;
  });
  pairing.forEach((j, i) => {
    if(pairing[j] !== i)
      throw new Error(`${MYNAME}: segment ${i} is paired with segment ${j}, but segment ${j} with segment ${pairing[j]}`);
    if(!sameTransform(subSides[j].trans, subSides[i].trans.getInverse(), testPoints))
      throw new Error(`${MYNAME}: the transform of segment ${j} is not the inverse of the one of segment ${i}`);
  });

  // ---- vertex cycles ---------------------------------------------------------------
  const visited = new Array(vertices.length).fill(false);
  const cycles = [];
  for(let v0 = 0; v0 < vertices.length; v0++){
    if(visited[v0] || vertices[v0].ideal) continue;
    const [sA, sB] = vertices[v0].subSides;
    // leave through the segment with the larger index and close through the other one
    let leave = Math.max(sA, sB);
    const closing = Math.min(sA, sB);
    let v = v0;
    const path = [], vertexPath = [];
    let angleSum = 0;
    for(let step = 0; ; step++){
      if(step > MAX_CYCLE_LENGTH)
        throw new Error(`${MYNAME}: the vertex cycle starting at vertex ${v0} does not close`);
      visited[v] = true;
      path.push(leave);
      vertexPath.push(v);
      angleSum += vertices[v].angle;
      const next = vertexAt(apply(subSides[leave].trans, vertices[v].point));
      const arriving = pairing[leave];
      if(next < 0 || !vertices[next].subSides.includes(arriving))
        throw new Error(`${MYNAME}: the transform of segment ${leave} does not map vertex ${v} onto a vertex of segment ${arriving}`);
      if(next === v0 && arriving === closing) break;
      v = next;
      leave = (vertices[v].subSides[0] === arriving) ? vertices[v].subSides[1] : vertices[v].subSides[0];
    }
    const ratio = 2*Math.PI/angleSum;
    const order = Math.round(ratio);
    if(order < 1 || Math.abs(ratio - order) > 1e-6)
      throw new Error(`${MYNAME}: the angles of the cycle at vertex ${v0} sum to ${angleSum}, not to a divisor of 2*PI`);
    cycles.push({ vertices: vertexPath, subSides: path, order });
  }

  // ---- relators --------------------------------------------------------------------
  // the walk around a vertex visits the cells D, g_x1(D), g_x1 g_x2(D), ...:
  // the cycle transform is g_x1 * g_x2 * ... * g_xk (g_xk applied first), which
  // in the left to right word convention is the word xk ... x2 x1
  const relatorList = [];
  const seen = new Set();
  const addRelator = (word, power) => {
    const reduced = freeReduce(word);
    if(reduced.length === 0) return;               // trivially true
    const key = `${relatorClass(reduced)}^${power}`;
    if(seen.has(key)) return;                      // the same relator read from elsewhere
    const relator = powerString(reduced, power);
    if(!sameTransform(evaluate(reduced, power), identity, testPoints))
      throw new Error(`${MYNAME}: relator ${relator} is not the identity`);
    seen.add(key);
    relatorList.push(relator);
  };

  subSides.forEach((s, i) => {
    const j = pairing[i];
    if(j === i)     addRelator(s.directWord, 2);
    else if(j > i)  addRelator(s.directWord + subSides[j].directWord, 1);
  });
  for(const cycle of cycles){
    const word = cycle.subSides.slice().reverse().map(x => subSides[x].directWord).join('');
    cycle.word = wordString(word);
    addRelator(word, cycle.order);
  }

  // a side with no arc of its own is a word in the others: the cell it leads to folds
  // back to the domain
  for(const k of spare){
    const T = fold(apply(direct[k], inner[0]));
    if(!T) throw new Error(`${MYNAME}: the cell of side ${k} does not fold into the domain`);
    if(freeReduce(names[k] + T.word).length === 0)
      throw new Error(`${MYNAME}: side ${k} bounds nothing and the other sides do not give its transform`);
    addRelator(names[k] + T.word, 1);
  }

  return {
    gens: names.join(' '),
    relators: relatorList.join(', '),
    genNames: names,
    relatorList,
    subSides: subSides.map(s => ({ side: s.side, t0: s.t0, t1: s.t1, word: s.word, directWord: s.directWord })),
    pairing,
    vertices,
    cycles,
  };
}

/**
  the presentation of the group of a group maker, for its getPresentation(), derived
  from the domain with groupPresentation. A deformation does not change the abstract
  group, so a maker with deformations derives from a copy of itself at its default
  values: this also holds for a twist too large for groupPresentation, and it keeps
  the presentation, which goes by the discrete parameters only, the same during a drag.

  maker: the group maker
  opt: {
    name:   name of the group
    label:  shown name, the name by default
    family: kind of group; catalogue names of wallpaper groups are for 'wallpaper'
    keep:   names of the discrete parameters in maker.params: the copy takes these
            and leaves the rest at their defaults
    key:    without keep, what the presentation depends on: it comes from the group
            of the maker itself and is derived again when the key changes
  }

  return {name, label, family, gens, relators}, null when the domain does not give one
*/
export function derivedPresentation(maker, opt){

  const { name, label = name, family, keep } = opt;
  const key = keep ? keep.map(k => maker.params[k]).join() : opt.key;
  if(maker.mPresentation && maker.mPresentation.key === key) return maker.mPresentation.value;

  let value = null;
  try {
    let group;
    if(keep){
      const copy = new maker.constructor();
      keep.forEach(k => { copy.params[k] = maker.params[k]; });
      group = copy.getGroup();
    } else {
      group = maker.getGroup();
    }
    if(group){
      const { gens, relators } = groupPresentation(group);
      value = { name, label, family, gens, relators };
    }
  } catch(e){
    console.warn(`${MYNAME}: no presentation of ${name}: ${e.message}`);
  }
  // the group of the maker may be a degenerate moment of a drag: its next one may do
  if(value || keep) maker.mPresentation = { key, value };
  return value;
}
