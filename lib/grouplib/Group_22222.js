import {
    TORADIANS,
    Group,
    EventProcessor,
    ParamFloat,
    ParamBool,
    setParamValues,
    iTransformU4,
    iLerpU4,
    chainOfOrthogonalCircles,
    toPoincareDisk,
}
from './modules.js';

const DEBUG = false;
const MYNAME = 'Group_22222';

/*
  group 22222 (a sphere with five cone points of order 2): the index-2 subgroup of the
  reflection group *22222 (Group_s22222) generated by the half turns about the corners of
  the right-angled pentagon.

  The fundamental domain is the pentagon together with its mirror image across the line
  x = 0 (S0): the sides S1, S2, S3, S4 of the pentagon and S3a, S2a, the images of S3 and
  S2 (S1 and S4 are centred on S0 and are their own images). The pairing transforms are
  the half turns [Si, S0] about the corners on S0: S1 and S4 are paired with themselves,
  S2 with S2a and S3 with S3a. The twists T0 and T1 change the pairings of S4 and of
  S2, S2a by splanes interpolated (iLerpU4) between sides orthogonal to the paired side,
  which keeps the side pairing while deforming the group.

  Imported from the Orb repo (examples/jslibm/Group_22222.js, 2026-10-26) with its
  parameter names, so the group blocks of the old presets load unchanged:
    R1, R2, R3   radii of the first three circles
    A2, A3, A4   directions (degrees) of the centres of the circles 2 and 3 and of the
                 closing circle, each from the centre of the previous one
    T0, T1       twists of the pairings of S4 and of S2, S2a
    uhp          the domain in the upper half plane, or reflected into the unit disk
*/
export class Group_22222 {

    constructor() {

        this.params = {
            R1: 0.2,
            R2: 0.2,
            R3: 0.2,
            A2: 0,
            A3: 0,
            A4: 0,
            T0: 0,
            T1: 0,
            uhp: true,
        };

        this.mParams = this.makeParams();
        this.state = {
            paramChanged: true,
            group: null,
        };
    }

    getClassName(){
        return MYNAME;
    }

    setOptions(opt){
        if(opt.onChanged){
            this.onGroupChanged = opt.onChanged;
            this.eventProcessor = new EventProcessor();
            this.eventProcessor.addEventListener('onChanged', this.onGroupChanged);
        }
    }

    //
    //  return external params
    //
    getParams(){
        return this.mParams;
    }

    makeParams() {

        const par = this.params;
        const opc = this.onParamChanged.bind(this);
        const radius = key => ParamFloat({obj: par, key: key, min: 0, max: 2, step: 0.001, onChange: opc});
        const angle  = key => ParamFloat({obj: par, key: key, min: -180, max: 180, step: 0.01, onChange: opc});
        const twist  = key => ParamFloat({obj: par, key: key, min: -1, max: 1, step: 0.001, onChange: opc});

        return {
            R1:  radius('R1'),
            R2:  radius('R2'),
            R3:  radius('R3'),
            A2:  angle('A2'),
            A3:  angle('A3'),
            A4:  angle('A4'),
            T0:  twist('T0'),
            T1:  twist('T1'),
            uhp: ParamBool({obj: par, key: 'uhp', onChange: opc}),
        };
    }

    //
    // called from UI when any group param was changed
    //
    onParamChanged() {

        this.state.paramChanged = true;
        if(DEBUG) console.log(`${MYNAME}.onParamChanged()`);
        if(this.eventProcessor){
            this.eventProcessor.handleEvent({type: 'onChanged', target: this});
        }
    }

    //
    // set parameters from saved paramMap
    //
    setParamsMap(paramsMap) {
        setParamValues(this.mParams, paramsMap);
    }

    //
    //  return group description
    //
    getGroup() {

        if(this.state.paramChanged) {
            this.state.group = this.calculateGroup();
            this.state.paramChanged = false;
        }
        return this.state.group;
    }

    calculateGroup(){

        const p = this.params;

        const [S0, S1, S2, S3, S4] = chainOfOrthogonalCircles([p.R1, p.R2, p.R3],
                                                             [p.A2, p.A3, p.A4].map(a => a*TORADIANS));
        // mirror images of S2 and S3 across S0
        const S2a = iTransformU4([S0], S2);
        const S3a = iTransformU4([S0], S3);

        const t0 = p.T0;
        const t1 = p.T1;
        const S03t  = iLerpU4(S0, S3,  t0);
        const S13at = iLerpU4(S1, S3a, t1);
        const S31t  = iLerpU4(S3, S1,  t1);

        let s = [S1, S2, S3, S4, S3a, S2a];
        // the transforms mapping the cell across each side back into the domain
        let t = [
            [S1, S0],
            (t1 == 0) ? [S2, S0] : [S31t, S3, S2, S0],
            [S3, S0],
            (t0 == 0) ? [S4, S0] : [S4, S0, S03t, S0],
            [S3a, S0],
            (t1 == 0) ? [S2a, S0] : [S13at, S1, S2a, S0],
        ];

        if(!p.uhp){
            // the Orb code reflected the sides only and left the transforms in the half
            // plane (no old preset has uhp off); the transforms follow here: a chain of
            // reflections conjugated by the reflection is the chain of the reflected splanes
            s = toPoincareDisk(s);
            t = t.map(chain => toPoincareDisk(chain));
        }

        const group = new Group({s: s, t: t});
        if(DEBUG) console.log(`${MYNAME} returning: `, group);
        return group;
    }

} // class Group_22222
