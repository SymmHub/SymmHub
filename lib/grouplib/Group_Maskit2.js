import {
    EventProcessor,
    ParamFloat,
    ParamInt,
    setParamValues,
    iPoint,
    cMul,
    cAdd,
    carrierGroup,
    dirichletDomain,
}
from './modules.js';

const DEBUG = false;
const MYNAME = 'Group_Maskit2';

/*
  Maskit's groups of the twice punctured torus (Mumford, Series, Wright: Indra's
  Pearls, chapter 11, p. 367; C. Series, The Maskit embedding of the twice punctured
  torus, Geom. Topol. 14 (2010)): the group generated by

      a = S1 = ( 1, 2 ; 0, 1 )            z -> z + 2, parabolic with the fixed point oo
      b = S2 = ( 1, 0 ; 2, 1 )            z -> z / (2 z + 1), parabolic with the fixed point 0
      c = T  = ( 1 + t1 t2, t1 ; t2, 1 )  with the complex parameters t1 = tau1, t2 = tau2

  (det T = 1 for every t1, t2). The free group on a, b, c is the fundamental group of
  a torus with two punctures; the punctures are the parabolic elements a B (trace -2,
  fixed point 1) and its partner across the handle c, and a, b themselves are the two
  curves pinched in the Maskit embedding. For Im t1 > 1, Im t2 > 1 and
  Im t1 Im t2 > 4 the group is discrete and free (Series, Proposition 2.1): the
  limit set lies in the strips 0 <= Im z <= 1/2 and Im t1 - 1/2 <= Im z <= Im t1
  (and oo), the region between them is the twice punctured torus' own component
  (its tiling is the picture of the book), the lower half plane and the half plane
  above Im t1 are the two triply punctured spheres of the pinched end. Parameters
  outside the region may give groups that are not discrete: the domain below is then
  no fundamental domain.

  The generators are written as reflection chains (carrierGroup in
  MobiusGenerators.js), the fundamental domain is the Dirichlet domain of the base
  point (baseX, baseY) (dirichletDomain there): the base belongs in the middle strip,
  the default is (0, Im t1 / 2). The side names of the group are its own (a, b, c,
  ...); its words in a, A, b, B, c, C are kept as dirichletWords.
*/
export class Group_Maskit2 {

    constructor() {

        this.params = {
            t1_re: 0,
            t1_im: 2.5,
            t2_re: 0,
            t2_im: 2.5,
            baseX: 0,
            baseY: 1.25,
            depth: 3,
            minScale: 0.001,
        };

        this.mParams = this.makeParams();
        this.state = {
            paramChanged: true,
            group: null,
        };
    }

    getClassName(){
        return MYNAME;
    }

    setOptions(opt){
        if(opt.onChanged){
            this.onGroupChanged = opt.onChanged;
            this.eventProcessor = new EventProcessor();
            this.eventProcessor.addEventListener('onChanged', this.onGroupChanged);
        }
    }

    //
    //  return external params
    //
    getParams(){
        return this.mParams;
    }

    makeParams() {

        const par = this.params;
        const opc = this.onParamChanged.bind(this);
        const tau = (key, name) => ParamFloat({obj: par, key: key, name: name, min: -4, max: 4, step: 1e-10, onChange: opc});
        const coord = key => ParamFloat({obj: par, key: key, min: -4, max: 4, step: 1e-10, onChange: opc});

        return {
            t1_re:    tau('t1_re', 'Re tau1'),
            t1_im:    tau('t1_im', 'Im tau1'),
            t2_re:    tau('t2_re', 'Re tau2'),
            t2_im:    tau('t2_im', 'Im tau2'),
            baseX:    coord('baseX'),
            baseY:    coord('baseY'),
            depth:    ParamInt({obj: par, key: 'depth', min: 1, max: 6, onChange: opc}),
            minScale: ParamFloat({obj: par, key: 'minScale', name: 'min scale', min: 0, max: 1, step: 1e-10, onChange: opc}),
        };
    }

    //
    // called from UI when any group param was changed
    //
    onParamChanged() {

        this.state.paramChanged = true;
        if(DEBUG) console.log(`${MYNAME}.onParamChanged()`);
        if(this.eventProcessor){
            this.eventProcessor.handleEvent({type: 'onChanged', target: this});
        }
    }

    //
    // set parameters from saved paramMap
    //
    setParamsMap(paramsMap) {
        setParamValues(this.mParams, paramsMap);
    }

    //
    //  the presentation of the generators, the sides of the carrier group: a free group
    //  of rank 3. The documents keep one permutation per generator whichever domain is
    //  drawn: sidePermutations takes them to the sides of a Dirichlet domain.
    //
    getPresentation() {
        return { name: 'Maskit 2-torus', label: 'Maskit 2-torus', family: 'free', gens: 'a b c d e f', relators: 'a*b, c*d, e*f' };
    }

    //
    //  return group description
    //
    getGroup() {

        if(this.state.paramChanged) {
            const group = this.calculateGroup();
            if(group) this.state.group = group;
            this.state.paramChanged = false;
        }
        return this.state.group;
    }

    //
    //  the generators: {a, b, c} as 2x2 complex matrices
    //
    getGenerators(){
        const p = this.params;
        return maskit2Generators([p.t1_re, p.t1_im], [p.t2_re, p.t2_im]);
    }

    calculateGroup(){

        const p = this.params;
        const {a, b, c} = this.getGenerators();
        const g0 = carrierGroup([{name: 'a', m: a}, {name: 'b', m: b}, {name: 'c', m: c}]);
        if(!g0){
            console.warn(`${MYNAME}: the generators of tau1 = ${p.t1_re} + ${p.t1_im} i, tau2 = ${p.t2_re} + ${p.t2_im} i are degenerate, the group is kept as it was`);
            return null;
        }
        const base = iPoint([p.baseX, p.baseY, 0, 0]);
        const dg = dirichletDomain(g0, base, p.depth, p.minScale);
        if(!dg){
            console.warn(`${MYNAME}: no Dirichlet domain at the base (${p.baseX}, ${p.baseY}) with words of ${p.depth} letters, the generators' own sides are used`);
            return g0;
        }
        if(DEBUG) console.log(`${MYNAME}: ${dg.getFundDomain().length} sides`, dg.dirichletWords);
        return dg;
    }

} // class Group_Maskit2


/**
  the generators of the twice punctured torus group of the parameters tau1, tau2
  (complex numbers [re, im]): {a, b, c} = {S1, S2, T}
*/
export function maskit2Generators(tau1, tau2){
    const one = [1, 0], zero = [0, 0];
    const a = [[one, [2, 0]], [zero, one]];
    const b = [[one, zero], [[2, 0], one]];
    const c = [[cAdd(one, cMul(tau1, tau2)), tau1], [tau2, one]];
    return {a, b, c};
}
